-- Mod Manager v2 story 4 (core 0.25.0): a single-line text box. Exposed as core.ui.textbox:
--   create{ id = <string>, text = <string|nil>, hint = <string|nil>, place = <intent|nil>, width = <number|nil>,
--           maxChars = <integer|nil>, tooltip = <tooltip|nil>, enabled = <boolean|nil>,
--           onChange = <function|nil>, onCommit = <function|nil> } -> handle
--   set(handle, text)               get(handle) -> text              setEnabled(handle, enabled)
--   setVisible(handle, visible)     setTooltip(handle, <tooltip> | nil)
--   remove(handle)                  isShown(handle) -> boolean
--
-- WBP_<Core>Textbox (generated by CoreGen): SizeBox "Frame" -> Border "Background" -> EditableText "Box", in the slider's
-- number box look (AlumniSans in the menu's text colour on the worn strip in the game look; the engine font on a dark box
-- in the plain look). width is 64-1024 canvas units (default 320); maxChars 1-256 (default 64); the hint (shown while
-- the box is empty) at most 64 bytes; text at most maxChars characters, valid UTF-8, no control characters.
--
-- Lua holds the text. Text read from the widget loses its control bytes and is cut to maxChars characters; when that
-- changed it, the cleaned text is written back to the box. onChange(handle, text) runs only when the cleaned text
-- differs from the last one (typing, a paste); onCommit(handle, text) on Enter or when the box loses keyboard focus (a
-- second commit of the same text within 250 ms, as Enter followed by its focus clear, is the same commit). Both run on
-- the game thread through C.callDependent inside pcall (cached assets only, as a control's onChange); a throwing callback
-- is logged once per text box and the box keeps working. set never calls back. enabled = false keeps it visible, dimmed
-- (the disabled opacity), and the box takes no input.
--
-- Focus (focus.lua): the field is focusable (its widget, a focusable class default) and gets the focus chip in a row.
-- Accept on the field gives the EditableText keyboard focus (typing); Enter commits and hands focus back to the field;
-- Escape while typing leaves the box for the field and keeps the text (the next Escape closes the window); a mouse click
-- types directly. Typing and committing move the window's focus model to the field without moving keyboard focus.
-- Search needs a keyboard: there is no gamepad virtual keyboard.
--
-- Dispatch: each dependent's Lua state registers one post-hook on <class>:<Core>_OnTextboxChanged and one on
-- <Core>_OnTextboxCommit, by full path, from the UI poll once a text box exists (never inside a hook). The hooks ignore
-- other mods' widgets in silence and a widget that isn't the element's current one, and read Box themselves.
local BASE = (...):gsub("%.ui%.textbox$", "")
local C = require(BASE .. ".ui.common")
local H = require(BASE .. ".ui.hud")
local P = require(BASE .. ".ui.place")
local X = require(BASE .. ".ui.text")
local A = require(BASE .. ".ui.assets")
local St = require(BASE .. ".ui.strings")
local theme = require(BASE .. ".ui.theme")

local TB = {}
local MIN_W, MAX_W, DEFAULT_W = 64, 1024, 320
local MAX_CHARS, DEFAULT_CHARS, MAX_HINT = 256, 64, 64
local COMMIT_SAME_US = 250000
local CREATE_KEYS = { id = true, text = true, hint = true, place = true, width = true, maxChars = true, tooltip = true,
    enabled = true, onChange = true, onCommit = true }
local S = { changes = 0, commits = 0, sameCommits = 0, cleaned = 0, ignored = 0, dropped = 0, throws = 0, typeInto = 0,
    hooked = false }
-- Set by focus.lua: typing(el) (the focus model moves to el, keyboard focus stays in the box) and committed(el) (the
-- same, then keyboard focus goes back to the field once nothing else of the window holds it).
TB.cb = {}

local function firstLine(e) return (tostring(e):match("^[^\n]*")) end
local function finite(v) return type(v) == "number" and v == v and v ~= math.huge and v ~= -math.huge end
local function keyList(t)
    local out = {}
    for k in pairs(t) do out[#out + 1] = k end
    table.sort(out)
    return table.concat(out, ", ")
end

-- ---------------------------------------------------------------- text (pure)

-- Characters in s (UTF-8), or nil when s isn't valid UTF-8.
local function charCount(s)
    local ok, n = pcall(utf8.len, s)
    if ok and n then return n end
    return nil
end

-- The text read from the widget, cleaned: control characters (C0 below 0x20, DEL 0x7F, C1 U+0080-U+009F) removed; text
-- that isn't valid UTF-8 loses every byte from 0x80 up (what is left is ASCII, so always valid); then cut to maxChars
-- characters. Returns the cleaned text and whether it changed. The result is always text set would accept.
local function clean(raw, maxChars)
    if type(raw) ~= "string" then return "", true end
    local s = raw:gsub("[%z\1-\31\127]", "")
    if not charCount(s) then s = s:gsub("[\128-\255]", "") end
    s = s:gsub("\194[\128-\159]", "")
    local n = charCount(s)
    if n > maxChars then s = s:sub(1, utf8.offset(s, maxChars + 1) - 1) end
    return s, s ~= raw
end
TB._clean = clean

-- ---------------------------------------------------------------- the kind

local function showText(el, w)
    C.count(); w:SetBoxText(el.text)
    el.shownText = el.text
end

local function applyEnabled(el, w)
    if el.appliedEnabled == el.enabled then return end
    C.count(); w:SetEnabledState(el.enabled)
    C.count(); w:SetRenderOpacity(el.enabled and 1 or theme.disabledOpacity)
    el.appliedEnabled = el.enabled
end

local function applyHint(el, w)
    local hint = el.hint or ""
    if hint == el.appliedHint then return end
    C.count(); w:SetHint(hint)
    el.appliedHint = hint
end

local function applyWidth(el, w)
    if el.appliedWidth == el.width then return end
    C.count(); w:SetWidth(el.width)
    el.appliedWidth = el.width
end

local function look(el, w)
    local g = theme.game
    if X._lookOf(el) == "game" then
        local strip, font = A.get("mat:strip"), A.get("font:" .. g.controlFont.font)
        if strip and font then
            if el.lookKey == "game" then return end
            local t = g.controlTint
            C.count(); w:SetBackgroundMaterial(strip, t.r, t.g, t.b, t.a, 0)
            C.count(); w:SetBoxLook(font, g.controlFont.size)
            el.lookKey = "game"
            return
        end
    end
    if el.lookKey == "plain" then return end
    local bg = theme.plainControl
    C.count(); w:SetBackgroundSolid()
    C.count(); w:SetBackground(bg.r, bg.g, bg.b, bg.a)
    local font = A.get("font:Engine")
    if font then C.count(); w:SetBoxLook(font, theme.plainControlFont) end
    el.lookKey = "plain"
end

X.KIND.textbox = {
    pkg = C.TEXTBOX_PKG, short = C.TEXTBOX_SHORT, cls = C.TEXTBOX_CLASS,
    content = function(el, w, fresh)
        if fresh then el.appliedHint, el.appliedEnabled, el.appliedWidth, el.lookKey = nil, true, nil, nil end
        applyWidth(el, w)
        showText(el, w)
        applyHint(el, w)
        applyEnabled(el, w)
        X._applyTooltip(el, w, fresh)
    end,
    style = function(el, w)
        el.chipOn = nil -- a re-style draws its own background (the UI tick puts a focus chip back)
        local ok, err = pcall(look, el, w)
        if not ok then C.warnOnce("look:" .. el.id, "text box '%s': its look was not applied (is %s's pak current?): %s", el.id, C.NAME, firstLine(err)) end
    end,
}

local function refresh(el, what)
    local w = X._liveWidget(el)
    if not w then return end
    local ok, err = pcall(function()
        if what.text then showText(el, w) end
        if what.hint then applyHint(el, w) end
        if what.width then applyWidth(el, w) end
        if what.enabled then applyEnabled(el, w) end
        if what.tooltip then X._applyTooltip(el, w, false) end
    end)
    if not ok then C.warnOnce("textbox:" .. el.id, "text box '%s': update failed (is %s's pak current?): %s", el.id, C.NAME, firstLine(err)) end
end

-- ---------------------------------------------------------------- the hooks (one each per Lua state)

local function chainVisible(el)
    local n = 0
    while el and n < 4 do
        if not el.visible then return false end
        el, n = el.panel, n + 1
    end
    return true
end

-- The element whose live widget fired, or nil (another mod's, a stale widget, disabled or hidden).
local function target(ctx)
    local w = ctx:get()
    if not C.valid(w) then return nil end
    local tag = X._readTag(w, "textbox")
    local mine = C.LOWER .. ":" .. C.modTag .. ":"
    if not tag or tag:sub(1, #mine) ~= mine then S.ignored = S.ignored + 1 return nil end -- another mod's text box
    local el = C.els[tag:sub(#mine + 1)]
    if not el or el.removed or el.kind ~= "textbox" then S.ignored = S.ignored + 1 return nil end
    local cur = el.ref and C.deref(el.ref)
    if not cur or cur:GetAddress() ~= w:GetAddress() then S.ignored = S.ignored + 1 return nil end -- not its live widget
    if not el.enabled or not chainVisible(el) then S.dropped = S.dropped + 1 return nil end
    return el, w
end

local function warnThrow(el, what, err)
    S.throws = S.throws + 1
    local key = "warned" .. what
    if not el[key] then
        el[key] = true
        C.log.warn("text box '%s' %s: %s", el.id, what, firstLine(err))
    end
end

-- Reads the box, cleans it (writing the cleaned text back when that changed it) and calls onChange when the text
-- changed. Core's own work runs with C.inDispatch raised (no asset load inside the hook).
local function readBox(el, w)
    local okT, raw = pcall(function() return w.Box:GetText():ToString() end)
    if not okT then
        C.warnOnce("textbox read:" .. el.id, "text box '%s': reading its text failed (is %s's pak current?): %s", el.id, C.NAME, firstLine(raw))
        return false
    end
    local text, changed = clean(raw, el.maxChars)
    local before = el.text
    el.text = text
    if changed then
        S.cleaned = S.cleaned + 1
        C.inDispatch = C.inDispatch + 1
        local okW, errW = pcall(showText, el, w) -- its own change event then reads the same text: no second onChange
        C.inDispatch = C.inDispatch - 1
        if not okW then C.warnOnce("textbox:" .. el.id, "text box '%s': writing the cleaned text back failed: %s", el.id, firstLine(errW)) end
    else
        el.shownText = text
    end
    if text == before then return false end
    S.changes = S.changes + 1
    if C.debugOn() then C.log.debug("ui textbox '%s' -> %d bytes", el.id, #text) end
    if el.onChange then
        local ok, err = C.callDependent(el.onChange, el.handle, text)
        if not ok then warnThrow(el, "onChange", err) end
    end
    return true
end

local function focusCb(name, el)
    local f = TB.cb[name]
    if not f then return end
    local ok, err = pcall(f, el)
    if not ok then C.warnOnce("textbox focus", "text box focus handling failed: %s", firstLine(err)) end
end

local function onChanged(ctx)
    local el, w = target(ctx)
    if not el then return end
    focusCb("typing", el)
    readBox(el, w)
end

local function onCommit(ctx)
    local el, w = target(ctx)
    if not el then return end
    readBox(el, w)
    local now = C.micros and C.micros() or nil
    local last = el.lastCommit
    if last and last.text == el.text and now and last.t and (now - last.t) < COMMIT_SAME_US then
        S.sameCommits = S.sameCommits + 1 -- Enter, then the focus clear it causes: one commit
    else
        el.lastCommit = { text = el.text, t = now }
        S.commits = S.commits + 1
        if C.debugOn() then C.log.debug("ui textbox '%s' commit", el.id) end
        if el.onCommit then
            local ok, err = C.callDependent(el.onCommit, el.handle, el.text)
            if not ok then warnThrow(el, "onCommit", err) end
        end
    end
    focusCb("committed", el)
end

-- focus.lua: Accept on the focused field gives the EditableText keyboard focus. True when it did.
function TB._typeInto(el, w)
    if not el.enabled or not chainVisible(el) then S.dropped = S.dropped + 1 return false end
    local ok, err = pcall(function() C.count(); w.Box:SetKeyboardFocus() end)
    if not ok then C.warnOnce("textbox type", "text box '%s': giving the box keyboard focus failed: %s", el.id, firstLine(err)) return false end
    S.typeInto = S.typeInto + 1
    return true
end

-- focus.lua: whether the element's EditableText holds keyboard focus (typing).
function TB._typing(el, w)
    local ok, yes = pcall(function() return w.Box:HasKeyboardFocus() end)
    return ok and yes == true
end

local function guarded(fn, what)
    return function(ctx)
        local ok, err = pcall(fn, ctx)
        if not ok then C.warnOnce("textbox dispatch", "text box %s handling failed: %s (further failures not logged)", what, firstLine(err)) end
    end
end
local hookChanged, hookCommit = guarded(onChanged, "change"), guarded(onCommit, "commit")

-- From the UI poll (never inside a hook), once a text box exists and its class is loaded.
local function ensureHooks()
    if S.hooked or X._inHook() then return S.hooked end
    if not X._classOf("textbox") then
        C.warnOnce("textbox hook class", "text box input can't be hooked yet: %s is not loaded (is Content/Paks/LogicMods/%s.pak installed?); retried at the next poll", C.TEXTBOX_CLASS, C.NAME)
        return false
    end
    local okA, errA = pcall(RegisterHook, C.TEXTBOX_CHANGED_FN, hookChanged)
    local okB, errB = pcall(RegisterHook, C.TEXTBOX_COMMIT_FN, hookCommit)
    S.hooked = true -- once only: a retry after a half registration would double one of them
    if okA and okB then C.log.debug("ui textbox hooks registered on %s and %s", C.TEXTBOX_CHANGED_FN, C.TEXTBOX_COMMIT_FN)
    else C.warnOnce("textbox hook", "text box input: RegisterHook failed (is %s's pak current?): %s", C.NAME, firstLine(okA and errB or errA)) end
    return true
end
H._host{ poll = function() end, reset = function() end, dispatch = function()
    if S.hooked then return nil end
    for _, el in ipairs(C.order) do
        if el.kind == "textbox" and not el.removed then ensureHooks() return nil end
    end
    return nil
end }

-- ---------------------------------------------------------------- validation

local function validWidth(v, pre)
    if v == nil then return DEFAULT_W end
    if not finite(v) or v < MIN_W or v > MAX_W then
        C.fail("%s: width must be a number from %d to %d (canvas units) or nil, got %s", pre, MIN_W, MAX_W, C.describe(v))
    end
    return v + 0.0
end

local function validMaxChars(v, pre)
    if v == nil then return DEFAULT_CHARS end
    if math.type(v) ~= "integer" and not (finite(v) and v == math.floor(v)) then
        C.fail("%s: maxChars must be an integer from 1 to %d or nil, got %s", pre, MAX_CHARS, C.describe(v))
    end
    if v < 1 or v > MAX_CHARS then C.fail("%s: maxChars must be an integer from 1 to %d or nil, got %s", pre, MAX_CHARS, C.describe(v)) end
    return math.tointeger(v)
end

local function validHint(v, pre)
    if v == nil then return nil end
    if type(v) ~= "string" or #v > MAX_HINT then C.fail("%s: hint must be a string of at most %d bytes or nil, got %s", pre, MAX_HINT, type(v) == "string" and (#v .. " bytes") or C.describe(v)) end
    if not charCount(v) then C.fail("%s: hint is not valid UTF-8", pre) end
    if v:find("[%z\1-\31\127]") or v:find("\194[\128-\159]") then C.fail("%s: hint must not contain control characters", pre) end
    return v
end

local function validText(v, maxChars, pre)
    if v == nil then return "" end
    if type(v) ~= "string" then C.fail("%s: text must be a string or nil, got %s", pre, C.describe(v)) end
    local n = charCount(v)
    if not n then C.fail("%s: text is not valid UTF-8", pre) end
    if n > maxChars then C.fail("%s: text is %d characters, at most %d (maxChars)", pre, n, maxChars) end
    if v:find("[%z\1-\31\127]") or v:find("\194[\128-\159]") then C.fail("%s: text must not contain control characters", pre) end
    return v
end

local function validFn(v, pre, what)
    if v == nil then return nil end
    if type(v) ~= "function" then C.fail("%s: %s must be a function or nil, got %s", pre, what, C.describe(v)) end
    return v
end

local function validBool(v, pre, what, default)
    if v == nil then return default end
    if type(v) ~= "boolean" then C.fail("%s: %s must be a boolean or nil, got %s", pre, what, C.describe(v)) end
    return v
end

-- ---------------------------------------------------------------- public

function TB.create(opts, ...)
    C.enter("textbox.create")
    local pre = C.UI .. ".textbox.create"
    if type(opts) ~= "table" then C.fail("%s: expected a table { id = ..., text = ..., onChange = ..., place = ... }, got %s", pre, C.describe(opts)) end
    if select("#", ...) > 0 then C.fail("%s: expected 1 argument (a table), got %d", pre, 1 + select("#", ...)) end
    for k in pairs(opts) do
        if not CREATE_KEYS[k] then C.fail("%s: unknown key %s (valid: %s)", pre, C.describe(k), keyList(CREATE_KEYS)) end
    end
    local id = X._validId(opts.id, "textbox.create")
    local width = validWidth(opts.width, pre)
    local maxChars = validMaxChars(opts.maxChars, pre)
    local hint = validHint(opts.hint, pre)
    local text = validText(opts.text, maxChars, pre)
    local onChange = validFn(opts.onChange, pre, "onChange")
    local onCommit = validFn(opts.onCommit, pre, "onCommit")
    local enabled = validBool(opts.enabled, pre, "enabled", true)
    local tooltip = St.validateTooltip(opts.tooltip, pre)
    if opts.place ~= nil and type(opts.place) ~= "table" then C.fail("%s: place must be a table or nil, got %s", pre, C.describe(opts.place)) end
    local intent = opts.place or { corner = "top-right" }
    local place = P.validate(intent)
    if not place.panelEl then X.checkHost("textbox", place.host, "textbox.create") end
    X._checkTipHost("textbox", place.panelEl and C.hostOf(place.panelEl) or place.host, tooltip ~= nil)
    local el = X._existing(id, "textbox", "textbox.create")
    if el then
        -- Same id: the new text, hint, width, limit, callbacks, enabled state, tooltip and intent.
        el.text, el.hint, el.width, el.maxChars = text, hint, width, maxChars
        el.onChange, el.onCommit, el.enabled, el.tooltip = onChange, onCommit, enabled, tooltip
        refresh(el, { text = true, hint = true, width = true, enabled = true, tooltip = true })
        P.place(el.handle, intent)
        return el.handle
    end
    if place.panelEl then X._checkJoin(place.panelEl, "textbox", "textbox.create", nil, tooltip ~= nil) end
    A.ensureLoadMapHook()
    el = X._new("textbox", id, { text = text, hint = hint, width = width, maxChars = maxChars, onChange = onChange,
        onCommit = onCommit, enabled = enabled, tooltip = tooltip, style = X.resolveStyle(nil, "textbox") }, place)
    return el.handle
end

function TB.get(h, ...)
    C.enter("textbox.get")
    local el = C.element(h, "textbox.get", "textbox")
    if select("#", ...) > 0 then C.fail("%s.textbox.get: expected 1 argument (handle), got %d", C.UI, 1 + select("#", ...)) end
    return el.text
end

function TB.set(h, ...)
    C.enter("textbox.set")
    local el = C.element(h, "textbox.set", "textbox")
    local n = select("#", ...)
    if n ~= 1 then C.fail("%s.textbox.set: expected 2 arguments (handle, text), got %d", C.UI, 1 + n) end
    local text = validText((...), el.maxChars, C.UI .. ".textbox.set")
    if text == el.text and text == el.shownText then return end -- no UObject call
    el.text = text
    refresh(el, { text = true })
end

function TB.setEnabled(h, enabled)
    C.enter("textbox.setEnabled")
    local el = C.element(h, "textbox.setEnabled", "textbox")
    if type(enabled) ~= "boolean" then C.fail("%s.textbox.setEnabled: enabled must be a boolean, got %s", C.UI, C.describe(enabled)) end
    if enabled == el.enabled then return end
    el.enabled = enabled
    refresh(el, { enabled = true })
    X._hostChanged(C.hostOf(el)) -- a disabled focused element hands keyboard focus on
end

function TB.setVisible(h, visible)
    C.enter("textbox.setVisible")
    local el = C.element(h, "textbox.setVisible", "textbox")
    if type(visible) ~= "boolean" then C.fail("%s.textbox.setVisible: visible must be a boolean, got %s", C.UI, type(visible)) end
    X._setVisible(el, visible)
end

function TB.remove(h)
    C.enter("textbox.remove")
    if type(h) == "table" and C.removedHandle[h] then return end -- idempotent
    local el = C.element(h, "textbox.remove", "textbox")
    X._remove(el)
end

function TB.isShown(h)
    C.enter("textbox.isShown")
    local el = C.element(h, "textbox.isShown", "textbox")
    return X._shown(el)
end

function TB.setTooltip(h, ...) return X._setTooltipOf("textbox", h, (...), 1 + select("#", ...)) end

function TB.stats()
    return { changes = S.changes, commits = S.commits, sameCommits = S.sameCommits, cleaned = S.cleaned, ignored = S.ignored,
        dropped = S.dropped, throws = S.throws, typeInto = S.typeInto, hooked = S.hooked }
end
TB._changed, TB._commit, TB._S, TB._ensureHooks = hookChanged, hookCommit, S, ensureHooks -- unit tests
TB._MIN_W, TB._MAX_W, TB._MAX_CHARS = MIN_W, MAX_W, MAX_CHARS
return TB
