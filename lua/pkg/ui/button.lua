-- UI-7 (story 15): buttons and click callbacks. Exposed as core.ui.button on the connect API:
--   create{ id = <string>, label = <string|number|nil>, place = <intent>, style = <style|nil>, onClick = <function>,
--           enabled = <boolean|nil>, icon = <source|nil>, iconSize = n | { w, h } | nil, dimmed = <boolean|nil>,
--           tooltip = <tooltip|nil> } -> handle
--   setLabel(handle, label)        setEnabled(handle, enabled)       setVisible(handle, visible)
--   remove(handle)                 isShown(handle) -> boolean        setTooltip(handle, <tooltip> | nil)
--   stats() -> table (diagnostic copy, not semver API)
--
-- Story 24 (core 0.8.0): an icon (a source as for ui.image: one of core's icons or an allow-listed game texture) left
-- of the label, 8 units apart, iconSize canvas units (default 24); with no label (nil or "") the button is the icon
-- alone and its box is exactly iconSize (no content padding, so it lines up with an image of that size); in the game
-- look an icon-only button has no face of its own, its icon lighting up on hover. dimmed draws the label and the icon
-- at the game's disabled colour (theme.dimmed) and hover doesn't brighten it; it stays clickable. enabled = false keeps
-- its look and drops clicks; its icon dims with it. A tooltip goes on the inner Button (text.lua).
--
-- The widget is WBP_<Core>Button (SizeBox "Box" -> Button "Btn" -> HorizontalBox "Content" -> SizeBox "IconBox" ->
-- Image "Icon", Spacer "IconGap", TextBlock "Label"), generated by CoreGen: SetLabel, SetEnabledState,
-- SetColors (face, hover and pressed colours plus padding: the theme's button presets), SetTag, and a Blueprint function
-- <Core>_OnClicked() that the button's OnClicked calls and that does nothing else but count (ClickCount). This is
-- bp-spike's proven pattern (docs/blueprint-mods.md Q3).
--
-- Dispatch: each dependent's Lua state registers ONE RegisterHook post-hook on <class path>:<Core>_OnClicked, by full
-- path, the first time it creates a button (core loads the button class before it calls onReady, story 15 decision 4).
-- UE4SS keys script hooks by the function's name chain, so the hook outlives a class unload and reload; one per state,
-- so no doubled hook. The hook reads the clicked widget's tag (<core>:<mod>:<id>, in CoreTag) and runs onClick only for
-- this mod's own button whose current widget it is; another mod's button is ignored in silence. onClick(handle) runs on
-- the game thread inside pcall: a throwing callback is logged once per button and the hook stays. Clicks on a disabled
-- or hidden button (or one in a hidden panel) are dropped, and so is a repeat within 250 ms (a double click is one).
--
-- Mod Manager story 4 (core 0.10.0): a checkbox (checkbox.lua) is this widget too, icon only. The same hook serves it:
-- the dispatch routes by the element's kind (B._kindDispatch), with the same tag, live-widget, enabled, visibility and
-- debounce rules; the class-to-kind lookups compare classes (text.lua, sameClass).
--
-- Where: only on hosts where the game shows a cursor ("journal", story 13), directly or in a panel there. On the HUD
-- the game's input is game-only and clicks never reach a widget (docs/blueprint-mods.md Q3): host = "hud" raises until
-- story 16 (input mode) lands.
