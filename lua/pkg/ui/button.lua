local function firstLine(e) return (tostring(e):match("^[^\n]*")) end

-- ---------------------------------------------------------------- the click hook (one per Lua state)

-- Story 21: core's own buttons (a window's Close) carry the tag <core>:<mod>:#<name>; ids of dependents' elements
-- can't start with "#". id -> fn() run on a click, under pcall.
B._internal = {}
-- Mod Manager story 4: other kinds on this widget class: kind -> fn(el, widget), run for a click that passed the
-- checks below (its own tag, its live widget, enabled and visible, not a repeat within 250 ms).
B._kindDispatch = {}
local lastInternal = {}

-- Whether an element and every container above it are visible (story 21: a row in a list is two levels down).
local function chainVisible(el)
    local n = 0
    while el and n < 4 do
        if not el.visible then return false end
        el, n = el.panel, n + 1
    end
    return true
end

local function dispatch(ctx)
    local w = ctx:get()
    if not C.valid(w) then return end
    local tag = X._readTag(w, "button")
    local mine = C.LOWER .. ":" .. C.modTag .. ":"
    if not tag or tag:sub(1, #mine) ~= mine then S.ignored = S.ignored + 1 return end -- another mod's button
    local id = tag:sub(#mine + 1)
    if id:sub(1, 1) == "#" then
        local f = B._internal[id]
        if not f then S.ignored = S.ignored + 1 return end
        local now = C.micros()
        if lastInternal[id] and now - lastInternal[id] < DEBOUNCE_US then S.debounced = S.debounced + 1 return end
        lastInternal[id] = now
        C.clickInput(id) -- core story 39: a click on a window's BACK is the mouse's (unless the Accept key's)
        local ok, err = pcall(f)
        if not ok then C.warnOnce("internal click " .. id, "core button %s: %s", id, firstLine(err)) end
        return
    end
    local el = C.els[id]
    if not el or el.removed or (el.kind ~= "button" and not B._kindDispatch[el.kind]) then S.ignored = S.ignored + 1 return end
    local cur = el.ref and C.deref(el.ref)
    if not cur or cur:GetAddress() ~= w:GetAddress() then S.ignored = S.ignored + 1 return end -- not its live widget
    if not el.enabled or not chainVisible(el) then S.dropped = S.dropped + 1 return end
    C.used(el) -- core story 27: a window's focus follows the mouse (and the Accept key, which clicks the focused Button)
    local now = C.micros()
    if el.lastClick and now - el.lastClick < DEBOUNCE_US then S.debounced = S.debounced + 1 return end
    el.lastClick = now
    local kd = B._kindDispatch[el.kind]
    if kd then return kd(el, w) end -- story 4: a checkbox toggles (checkbox.lua)
    S.clicks = S.clicks + 1
    el.clicks = (el.clicks or 0) + 1
    if C.debugOn() then C.log.debug("ui button '%s' clicked (%d)", el.id, el.clicks) end
    local ok, err = C.callDependent(el.onClick, el.handle) -- core story 37: no load or hook registration inside the hook
    if not ok then
        S.throws = S.throws + 1
        if not el.warnedClick then
            el.warnedClick = true
            C.log.warn("button '%s' onClick: %s", el.id, firstLine(err))
        end
    end
end

local function onClicked(ctx)
    local ok, err = pcall(dispatch, ctx)
    if not ok then C.warnOnce("click dispatch", "button click handling failed: %s (further failures not logged)", firstLine(err)) end
end

-- Registers the hook once the button class is loaded; false (and one WARN) while it can't.
local function ensureHook()
    if S.hooked then return true end
    -- Story 20: never registered from inside the Journal's Construct hook; the poll tick registers it (below).
    if X._inHook and X._inHook() then return false end
    if not X._classOf("button") then
        C.warnOnce("button hook class", "button clicks can't be hooked yet: %s is not loaded (is Content/Paks/LogicMods/%s.pak installed?); retried at the next attach", C.BUTTON_CLASS, C.NAME)
        return false
    end
    S.hookTries = S.hookTries + 1
    local ok, pre = pcall(RegisterHook, C.CLICK_FN, onClicked)
    if ok then
        S.hooked, S.hookId = true, pre
        C.log.debug("ui button click hook registered on %s (id %s)", C.CLICK_FN, tostring(pre))
    else
        C.warnOnce("button hook", "button clicks: RegisterHook(%s) failed: %s", C.CLICK_FN, firstLine(pre))
    end
    return S.hooked
end

-- Story 20: buttons can be attached inside the Journal's Construct hook, where no hook is registered: the poll tick
-- that checks the Construct hook registers the click hook first, once a button exists.
local function pollHook()
    if S.hooked then return end
    for _, el in ipairs(C.order) do
        if el.kind == "button" and not el.removed then ensureHook() return end
    end
end
X._pollHooks[#X._pollHooks + 1] = pollHook
-- Core story 37: a state's first button made inside a dependent's callback (create and attach register no hook there):
-- the UI tick registers it (never inside a hook; once hooked this is one check).
H._host{ poll = function() end, reset = function() end, dispatch = function()
    if not S.hooked and not X._inHook() then pollHook() end
    return nil
end }

-- ---------------------------------------------------------------- the kind (text.lua's engine)

local function applyEnabled(el, w)
    if el.appliedEnabled == el.enabled then return end
    C.count(); w:SetEnabledState(el.enabled)
    C.count(); w:SetRenderOpacity(el.enabled and 1 or theme.disabledOpacity)
    el.appliedEnabled = el.enabled
end

-- Story 21: the game's look on a button widget (the menu's secondary buttons: M_NN_WornStrip at alpha 0.52, the
-- cinematic selection on hover and press, AlumniSans-SemiBold 22 in the menu's text colours, padding 12/4/12/4, at
-- least 44 high). False when an asset is missing (the caller keeps the plain look; assets.lua warned once).
-- Story 24: dimmed, the face doesn't light up on hover either (the strip in every state).
local function styleGame(w, dimmed)
    local g = theme.game
    local strip, sel = A.get("mat:strip"), A.get("mat:selection")
    local font = A.get("font:" .. g.buttonFont.font)
    if not (strip and sel and font) then return false end
    local t, pd, n, h = g.buttonTint, g.buttonPadding, g.text, g.textHover
    C.count(); w:SetMaterials(strip, dimmed and strip or sel, t.r, t.g, t.b, t.a, pd.l, pd.t, pd.r, pd.b, g.buttonMinHeight)
    C.count(); w:SetLabelLook(font, g.buttonFont.size, n.r, n.g, n.b, n.a, h.r, h.g, h.b, h.a, g.shadowA)
    return true
end
function B._styleGame(w, dimmed)
    local ok, res = pcall(styleGame, w, dimmed)
    if not ok then C.warnOnce("game button", "a game-look button failed (is %s's pak current?): %s", C.NAME, firstLine(res)) return false end
    return res
end

-- Story 24: the label's and the icon's colours (normal, hover): dimmed, both the game's disabled colour; else the
-- game's text colours on a game face, white on a plain one (the generator's). el.colorKey: what the widget has now.
-- Core story 42: ownColors(el) -> key, normal, hover: the colours its own style gives it (also a chipped checkbox's).
local function ownColors(el)
    if el.dimmed then return "dim", theme.dimmed, theme.dimmed
    elseif el.gameFace then return "game", theme.game.text, theme.game.textHover end
    return "plain", theme.white, theme.white
end
local function applyColors(el, w)
    local key, n, h = ownColors(el)
    if key == el.colorKey then return end
    C.count(); w:SetContentColors(n.r, n.g, n.b, n.a, h.r, h.g, h.b, h.a)
    el.colorKey = key
end

local function iconOnly(el) return el.icon ~= nil and el.label == "" end

-- Core story 42 (0.17.1): the box behind a chipped checkbox's icon (WBP_<Core>Button's IconBack, SetIconBack): shown in
-- theme.game.focusChipBack while the checkbox is chipped, so its transparent inside stays dark (the light chip shows
-- only as the ring around it); hidden by its own style when the chip leaves. el.backOn: the widget shows it now. A pak
-- without SetIconBack (older than 0.17.1) or a failing call: one WARN naming the focus chip, then it is never shown
-- again in this Lua state (the checkbox keeps its own colours on the chip, without the dark inside); a hide is still
-- tried, so a box shown before the failure doesn't stay after its chip leaves.
local backGone = false
local function iconBack(el, w, show)
    if backGone and show then return end
    local c = theme.game.focusChipBack
    local ok, err = pcall(function() C.count(); w:SetIconBack(show, c.r, c.g, c.b, c.a) end)
    if ok then el.backOn = show or nil return end
    backGone, el.backOn = true, nil
    C.warnOnce("focus chip back", "checkbox '%s': the focus chip's dark inside (SetIconBack) failed (is %s's pak current?): %s; a chipped checkbox shows the chip through its inside",
        el.id, C.NAME, firstLine(err))
end
B._resetIconBack = function() backGone = false end

-- Story 24: the icon and the layout. Label only (no icon): the 0.7.0 widget. Icon and label: the icon (iconSize) left
-- of the label, the gap between them. Icon only: the label and gap collapsed, the box exactly iconSize. el.iconKey:
-- the texture and size the widget's icon has now (false: none); el.layoutKey: the layout it has now.
local applyIconLater -- below
local function applyIcon(el, w, fresh)
    if fresh then el.iconKey, el.layoutKey = false, "label" end
    local tex, key = nil, nil
    if el.icon then
        tex, key = I._resolve(el.icon)
        if key == "pending" then I._later(el, applyIconLater) return end -- inside a hook, not cached: the next UI tick
    end
    local sz = el.iconSize
    local want = tex and string.format("%s@%gx%g", key, sz.w, sz.h) or false
    if want ~= el.iconKey then
        if tex then C.count(); w:SetIcon(tex, sz.w, sz.h) else C.count(); w:ClearIcon() end
        el.iconKey = want
    end
    local layout
    if not el.icon then layout = "label"
    elseif el.label == "" then layout = string.format("only@%gx%g", sz.w, sz.h)
    elseif tex then layout = "both"
    else layout = "label" end
    if layout == el.layoutKey then return end
    local V = C.VIS
    if layout:sub(1, 4) == "only" then
        C.count(); w.Box:SetWidthOverride(sz.w)
        C.count(); w.Box:SetHeightOverride(sz.h)
        C.count(); w.Label:SetVisibility(V.Collapsed)
        C.count(); w.IconGap:SetVisibility(V.Collapsed)
    else
        if el.layoutKey and el.layoutKey:sub(1, 4) == "only" then
            C.count(); w.Box:ClearWidthOverride()
            C.count(); w.Box:ClearHeightOverride()
            C.count(); w.Label:SetVisibility(V.HitTestInvisible)
        end
        C.count(); w.IconGap:SetVisibility(layout == "both" and V.HitTestInvisible or V.Collapsed)
    end
    el.layoutKey = layout
end

-- The next tick's apply of an icon missed inside a hook: the button may grow, so its container's slots and what
-- follows it in its corner are refreshed too.
applyIconLater = function(el, w)
    applyIcon(el, w, false)
    if el.panel then X._applyGaps(el.panel) end
    X._resized(el)
end

local PLAIN_LABEL = { size = 18 }
