-- UI-11 (Mod Manager story 4, core 0.10.0, core story 26): sliders with a number box. Exposed as core.ui.slider:
--   create{ id = <string>, min = <number>, max = <number>, step = <number>, value = <number|nil>,
--           defaultValue = <number|nil>, hint = <string|nil>, onChange = <function>, place = <intent|nil>,
--           enabled = <boolean|nil>, tooltip = <tooltip|nil> } -> handle
--   get(handle) -> value | nil      set(handle, value | nil)         setDefault(handle, defaultValue, hint | nil)
--   setEnabled(handle, enabled)     setVisible(handle, visible)      remove(handle)
--   isShown(handle) -> boolean      setTooltip(handle, <tooltip> | nil)
--
-- A slider and a number box side by side (WBP_<Core>Slider, generated by CoreGen). min < max, step > 0, at most 10,000
-- steps; value and defaultValue finite and inside min..max (defaultValue defaults to min); the hint at most 64 bytes.
-- value nil is Default: the box is empty and shows the hint, and the slider sits at defaultValue.
--
-- The sync between the two lives in the Blueprint, never in Lua: the drag snaps to step and writes the box on every
-- frame (Conv_DoubleToText with the step's decimals) with no Lua call. Lua hears only the end of a drag (mouse or
-- controller capture end) and the box's commit (Enter, or focus lost). On a commit it parses the text ("." or "," as
-- the decimal mark), clamps it to min..max and rounds it to min + k * step; unparsable or non-finite text restores the
-- last value; an empty box means Default (nil). onChange(handle, value) runs on the game thread inside pcall, exactly
-- once per real change (the end of a drag or a commit that changes the value), never for set, setDefault or a commit
-- that leaves the value as it was. A throwing onChange is logged once per slider and the slider keeps working.
-- setDefault moves a slider that is at Default and leaves a custom value alone; its hint argument left out keeps the
-- current hint, an explicit nil clears it. value and defaultValue (on create, set and setDefault) are snapped to
-- min + k * step, so the slider never holds a value a drag or a commit would change. The number box widens while it
-- shows a hint (room for 16 characters). enabled = false keeps it visible,
-- dimmed (the disabled opacity) and ignores input: read-only settings use it.
--
-- Look: the bar and handle are copied from the game's Settings menu slider (the SettingsMenu_C widget-tree template,
-- loaded by path at runtime) in the game look; when it can't be read, the widget's generated copy of that style stays,
-- with one WARN. The number box is AlumniSans in the menu's text colour on the worn strip (game look) or the engine font
-- on a dark box (plain). The slider is not focusable: keyboard edits go through the box.
--
-- Dispatch: each dependent's Lua state registers one post-hook on <class>:<Core>_OnSliderEnd and one on
-- <Core>_OnSliderCommit, by full path, from the UI poll once a slider exists (never inside a hook). The hooks ignore
-- other mods' widgets in silence and a widget that isn't the element's current one.
local BASE = (...):gsub("%.ui%.slider$", "")
local C = require(BASE .. ".ui.common")
local H = require(BASE .. ".ui.hud")
local P = require(BASE .. ".ui.place")
local X = require(BASE .. ".ui.text")
local A = require(BASE .. ".ui.assets")
local I = require(BASE .. ".ui.image")
local CH = require(BASE .. ".ui.choice")
local St = require(BASE .. ".ui.strings")
local theme = require(BASE .. ".ui.theme")

local SL = {}
local MAX_STEPS, MAX_HINT = 10000, 64
local CREATE_KEYS = { id = true, min = true, max = true, step = true, value = true, defaultValue = true, hint = true,
    onChange = true, place = true, enabled = true, tooltip = true }
local S = { ends = 0, commits = 0, changes = 0, nudges = 0, restored = 0, ignored = 0, dropped = 0, throws = 0, hooked = false }

local function firstLine(e) return (tostring(e):match("^[^\n]*")) end
local function finite(v) return type(v) == "number" and v == v and v ~= math.huge and v ~= -math.huge end
local function keyList(t)
    local out = {}
    for k in pairs(t) do out[#out + 1] = k end
    table.sort(out)
    return table.concat(out, ", ")
end

-- ---------------------------------------------------------------- numbers (pure)

-- v clamped to min..max and rounded to min + k * step (k an integer; never past max), as a clean double.
local function snap(v, min, max, step)
    if v <= min then return min end
    local kmax = math.floor((max - min) / step + 1e-9)
    local k = math.floor((v - min) / step + 0.5)
    if k > kmax then k = kmax end
    if k < 0 then k = 0 end
    return tonumber(string.format("%.10g", min + k * step))
end
SL._snap = snap

-- The box's text -> "empty" | "ok", number | "bad". "." or "," is the decimal mark; spaces around are ignored; only
-- plain decimal numbers (an optional sign, digits, one mark) are numbers.
local function parse(text)
    if type(text) ~= "string" then return "bad" end
    local t = text:match("^%s*(.-)%s*$")
    if t == "" then return "empty" end
    t = t:gsub(",", ".")
    if not t:match("^[+-]?%d*%.?%d*$") or not t:match("%d") then return "bad" end
    local v = tonumber(t)
    if not finite(v) then return "bad" end
    return "ok", v
end
SL._parse = parse

local function decimalsFor(min, step) return math.max(CH._decimalsOf(step), CH._decimalsOf(min)) end

-- ---------------------------------------------------------------- the kind

-- The game's Settings slider style on the bar (game look). A miss inside a hook is copied on the next UI tick.
local copyLater -- below
local function copyStyle(el, w, later)
    if el.styleCopied then return end
    local tmpl, why = A.sliderTemplate()
    if not tmpl then
        if why == "uncached" then I._later(el, copyLater) end
        return -- "missing": assets.lua warned once; the generated copy of the style stays
    end
    C.count(); w:CopySliderStyle(tmpl)
    el.styleCopied = true
    if later and el.enabled then
        -- A painted slider takes the new style on its next invalidation: force one.
        C.count(); w:SetEnabledState(false)
        C.count(); w:SetEnabledState(true)
    end
end
copyLater = function(el, w) copyStyle(el, w, true) end

local function showValue(el, w)
    if el.value ~= nil then C.count(); w:SetSliderValue(el.value)
    else C.count(); w:SetSliderEmpty(el.default) end
    el.shown = el.value == nil and ("d" .. el.default) or el.value
end

local function applyEnabled(el, w)
    if el.appliedEnabled == el.enabled then return end
    C.count(); w:SetEnabledState(el.enabled)
    C.count(); w:SetRenderOpacity(el.enabled and 1 or theme.disabledOpacity)
    el.appliedEnabled = el.enabled
end

-- The number box is BOX_W wide, BOX_HINT_W while it has a hint (room for a hint of 16 characters).
local BOX_W, BOX_HINT_W = 112, 200
local function applyHint(el, w)
    local hint = el.hint or ""
    if hint == el.appliedHint then return end
    local width = hint ~= "" and BOX_HINT_W or BOX_W
    if width ~= el.boxWidth then C.count(); w:SetBoxWidth(width); el.boxWidth = width end
    C.count(); w:SetHint(hint)
    el.appliedHint = hint
end
SL._BOX_W, SL._BOX_HINT_W = BOX_W, BOX_HINT_W

local function applyRange(el, w)
    local key = string.format("%.17g/%.17g/%.17g/%d", el.min, el.max, el.step, el.decimals)
    if key == el.rangeKey then return end
    C.count(); w:SetRange(el.min, el.max, el.step, el.decimals)
    el.rangeKey = key
end

local function look(el, w)
    local g = theme.game
    if X._lookOf(el) == "game" then
        copyStyle(el, w, false)
        local strip, font = A.get("mat:strip"), A.get("font:" .. g.controlFont.font)
        if strip and font then
            if el.lookKey == "game" then return end
            local t = g.controlTint
            C.count(); w:SetBackgroundMaterial(strip, t.r, t.g, t.b, t.a, 0)
            C.count(); w:SetBoxLook(font, g.controlFont.size)
            el.lookKey = "game"
            return
        end
    end
    if el.lookKey == "plain" then return end
    local bg = theme.plainControl
    C.count(); w:SetBackgroundSolid()
    C.count(); w:SetBackground(bg.r, bg.g, bg.b, bg.a)
    local font = A.get("font:Engine")
    if font then C.count(); w:SetBoxLook(font, theme.plainControlFont) end
    el.lookKey = "plain"
end

X.KIND.slider = {
    pkg = C.SLIDER_PKG, short = C.SLIDER_SHORT, cls = C.SLIDER_CLASS,
    content = function(el, w, fresh)
        if fresh then el.rangeKey, el.appliedHint, el.appliedEnabled, el.styleCopied, el.lookKey, el.boxWidth = nil, nil, true, nil, nil, BOX_W end
        applyRange(el, w)  -- before the value: the bar clamps to its range
        showValue(el, w)
        applyHint(el, w)
        applyEnabled(el, w)
        X._applyTooltip(el, w, fresh)
    end,
    style = function(el, w)
        local ok, err = pcall(look, el, w)
        if not ok then C.warnOnce("look:" .. el.id, "slider '%s': its look was not applied (is %s's pak current?): %s", el.id, C.NAME, firstLine(err)) end
    end,
}

local function refresh(el, what)
    local w = X._liveWidget(el)
    if not w then return end
    local ok, err = pcall(function()
        if what.range then applyRange(el, w) end
        if what.value then showValue(el, w) end
        if what.hint then applyHint(el, w) end
        if what.enabled then applyEnabled(el, w) end
        if what.tooltip then X._applyTooltip(el, w, false) end
    end)
    if not ok then C.warnOnce("slider:" .. el.id, "slider '%s': update failed (is %s's pak current?): %s", el.id, C.NAME, firstLine(err)) end
end

-- ---------------------------------------------------------------- the hooks (one each per Lua state)

local function chainVisible(el)
    local n = 0
    while el and n < 4 do
        if not el.visible then return false end
        el, n = el.panel, n + 1
    end
    return true
end

-- The element whose live widget fired, or nil (another mod's, a stale widget, disabled or hidden).
local function target(ctx)
    local w = ctx:get()
    if not C.valid(w) then return nil end
    local tag = X._readTag(w, "slider")
    local mine = C.LOWER .. ":" .. C.modTag .. ":"
    if not tag or tag:sub(1, #mine) ~= mine then S.ignored = S.ignored + 1 return nil end -- another mod's slider
    local el = C.els[tag:sub(#mine + 1)]
    if not el or el.removed or el.kind ~= "slider" then S.ignored = S.ignored + 1 return nil end
    local cur = el.ref and C.deref(el.ref)
    if not cur or cur:GetAddress() ~= w:GetAddress() then S.ignored = S.ignored + 1 return nil end -- not its live widget
    if not el.enabled or not chainVisible(el) then S.dropped = S.dropped + 1 return nil end
    C.used(el) -- core story 27: a window's focus follows the mouse
    return el, w
end

-- Shows the element's value again (core's own work inside the hook: no asset load), then calls back when changed.
local function settle(el, w, changed)
    C.inDispatch = C.inDispatch + 1
    local okS, errS = pcall(showValue, el, w)
    C.inDispatch = C.inDispatch - 1
    if not okS then C.warnOnce("slider:" .. el.id, "slider '%s': showing its value failed: %s", el.id, firstLine(errS)) end
    if not changed then return end
    S.changes = S.changes + 1
    if C.debugOn() then C.log.debug("ui slider '%s' -> %s", el.id, tostring(el.value)) end
    local ok, err = C.callDependent(el.onChange, el.handle, el.value) -- core story 37: no load inside the hook
    if not ok then
        S.throws = S.throws + 1
        if not el.warnedChange then
            el.warnedChange = true
            C.log.warn("slider '%s' onChange: %s", el.id, firstLine(err))
        end
    end
end

local function onEnd(ctx)
    local el, w = target(ctx)
    if not el then return end
    S.ends = S.ends + 1
    local okV, raw = pcall(function() return w.Bar:GetValue() end)
    if not (okV and finite(tonumber(raw))) then settle(el, w, false) return end
    local v = snap(tonumber(raw), el.min, el.max, el.step)
    -- A click on the handle of a Default slider that doesn't move it keeps Default.
    if el.value == nil and v == snap(el.default, el.min, el.max, el.step) then settle(el, w, false) return end
    local changed = v ~= el.value
    el.value = v
    settle(el, w, changed)
end

local function onCommit(ctx)
    local el, w = target(ctx)
    if not el then return end
    S.commits = S.commits + 1
    local okT, text = pcall(function() return w.Box:GetText():ToString() end)
    local st, v = parse(okT and text or nil)
    if st == "bad" then S.restored = S.restored + 1 settle(el, w, false) return end
    if st == "ok" then v = snap(v, el.min, el.max, el.step) end
    local changed = v ~= el.value
    el.value = v
    settle(el, w, changed)
end

-- Core story 27: Left / Right on the focused slider: value +- step, clamped to min..max (a Default slider starts from
-- defaultValue); onChange once when the value changed. True when it changed.
function SL._nudge(el, w, dir)
    if not el.enabled or not chainVisible(el) then S.dropped = S.dropped + 1 return false end
    local base = el.value ~= nil and el.value or el.default
    local v = snap(base + dir * el.step, el.min, el.max, el.step)
    if v == base then return false end -- a Default slider at its end stays Default
    el.value = v
    S.nudges = S.nudges + 1
    settle(el, w, true)
    return true
end

local function guarded(fn, what)
    return function(ctx)
        local ok, err = pcall(fn, ctx)
        if not ok then C.warnOnce("slider dispatch", "slider %s handling failed: %s (further failures not logged)", what, firstLine(err)) end
    end
end
local hookEnd, hookCommit = guarded(onEnd, "drag end"), guarded(onCommit, "commit")

-- From the UI poll (never inside a hook), once a slider exists and its class is loaded.
local function ensureHooks()
    if S.hooked or X._inHook() then return S.hooked end
    if not X._classOf("slider") then
        C.warnOnce("slider hook class", "slider input can't be hooked yet: %s is not loaded (is Content/Paks/LogicMods/%s.pak installed?); retried at the next poll", C.SLIDER_CLASS, C.NAME)
        return false
    end
    local okE, errE = pcall(RegisterHook, C.SLIDER_END_FN, hookEnd)
    local okC, errC = pcall(RegisterHook, C.SLIDER_COMMIT_FN, hookCommit)
    S.hooked = true -- once only: a retry after a half registration would double one of them
    if okE and okC then C.log.debug("ui slider hooks registered on %s and %s", C.SLIDER_END_FN, C.SLIDER_COMMIT_FN)
    else C.warnOnce("slider hook", "slider input: RegisterHook failed: %s", firstLine(okE and errC or errE)) end
    return true
end
H._host{ poll = function() end, reset = function() end, dispatch = function()
    if S.hooked then return nil end
    for _, el in ipairs(C.order) do
        if el.kind == "slider" and not el.removed then ensureHooks() return nil end
    end
    return nil
end }

-- ---------------------------------------------------------------- validation

local function validRange(opts, pre)
    for _, k in ipairs({ "min", "max", "step" }) do
        if not finite(opts[k]) then C.fail("%s: %s must be a finite number, got %s", pre, k, C.describe(opts[k])) end
    end
    local min, max, step = opts.min + 0.0, opts.max + 0.0, opts.step + 0.0
    if min >= max then C.fail("%s: min (%s) must be less than max (%s)", pre, C.describe(opts.min), C.describe(opts.max)) end
    if step <= 0 then C.fail("%s: step must be greater than 0, got %s", pre, C.describe(opts.step)) end
    local n = (max - min) / step
    if not (n <= MAX_STEPS + 1e-9) then C.fail("%s: min..max in steps of %s is %s steps, at most %d", pre, C.describe(opts.step), n == n and string.format("%.0f", n) or "too many", MAX_STEPS) end
    return min, max, step
end

local function validValue(v, min, max, pre, what, allowNil)
    if v == nil and allowNil then return nil end
    if not finite(v) then C.fail("%s: %s must be a finite number%s, got %s", pre, what, allowNil and " or nil" or "", C.describe(v)) end
    if v < min or v > max then C.fail("%s: %s %s is outside %.10g..%.10g", pre, what, C.describe(v), min, max) end
    return v + 0.0
end

local function validHint(v, pre)
    if v == nil then return nil end
    if type(v) ~= "string" or #v > MAX_HINT then C.fail("%s: hint must be a string of at most %d bytes or nil, got %s", pre, MAX_HINT, type(v) == "string" and (#v .. " bytes") or C.describe(v)) end
    return v
end

local function validBool(v, pre, what, default)
    if v == nil then return default end
    if type(v) ~= "boolean" then C.fail("%s: %s must be a boolean or nil, got %s", pre, what, C.describe(v)) end
    return v
end

-- ---------------------------------------------------------------- public

function SL.create(opts, ...)
    C.enter("slider.create")
    local pre = C.UI .. ".slider.create"
    if type(opts) ~= "table" then C.fail("%s: expected a table { id = ..., min = ..., max = ..., step = ..., onChange = ..., place = ... }, got %s", pre, C.describe(opts)) end
    if select("#", ...) > 0 then C.fail("%s: expected 1 argument (a table), got %d", pre, 1 + select("#", ...)) end
    for k in pairs(opts) do
        if not CREATE_KEYS[k] then C.fail("%s: unknown key %s (valid: %s)", pre, C.describe(k), keyList(CREATE_KEYS)) end
    end
    local id = X._validId(opts.id, "slider.create")
    local min, max, step = validRange(opts, pre)
    -- Values are snapped to min + k * step, so a commit or a click that doesn't move the slider is never a change.
    local value = validValue(opts.value, min, max, pre, "value", true)
    if value ~= nil then value = snap(value, min, max, step) end
    local default = opts.defaultValue == nil and min or snap(validValue(opts.defaultValue, min, max, pre, "defaultValue", false), min, max, step)
    local hint = validHint(opts.hint, pre)
    if type(opts.onChange) ~= "function" then C.fail("%s: onChange must be a function, got %s", pre, C.describe(opts.onChange)) end
    local enabled = validBool(opts.enabled, pre, "enabled", true)
    local tooltip = St.validateTooltip(opts.tooltip, pre)
    if opts.place ~= nil and type(opts.place) ~= "table" then C.fail("%s: place must be a table or nil, got %s", pre, C.describe(opts.place)) end
    local intent = opts.place or { corner = "top-right" }
    local place = P.validate(intent)
    if not place.panelEl then X.checkHost("slider", place.host, "slider.create") end
    X._checkTipHost("slider", place.panelEl and C.hostOf(place.panelEl) or place.host, tooltip ~= nil)
    local decimals = decimalsFor(min, step)
    local el = X._existing(id, "slider", "slider.create")
    if el then
        -- Same id: the new range, value, default, hint, callback, enabled state, tooltip and intent.
        el.min, el.max, el.step, el.decimals = min, max, step, decimals
        el.value, el.default, el.hint, el.onChange, el.enabled, el.tooltip = value, default, hint, opts.onChange, enabled, tooltip
        refresh(el, { range = true, value = true, hint = true, enabled = true, tooltip = true })
        P.place(el.handle, intent)
        return el.handle
    end
    if place.panelEl then X._checkJoin(place.panelEl, "slider", "slider.create", nil, tooltip ~= nil) end
    A.ensureLoadMapHook()
    el = X._new("slider", id, { min = min, max = max, step = step, decimals = decimals, value = value, default = default,
        hint = hint, onChange = opts.onChange, enabled = enabled, tooltip = tooltip, style = X.resolveStyle(nil, "slider") }, place)
    return el.handle
end

function SL.get(h, ...)
    C.enter("slider.get")
    local el = C.element(h, "slider.get", "slider")
    if select("#", ...) > 0 then C.fail("%s.slider.get: expected 1 argument (handle), got %d", C.UI, 1 + select("#", ...)) end
    return el.value
end

function SL.set(h, ...)
    C.enter("slider.set")
    local el = C.element(h, "slider.set", "slider")
    local n = select("#", ...)
    if n ~= 1 then C.fail("%s.slider.set: expected 2 arguments (handle, value or nil), got %d", C.UI, 1 + n) end
    local v = validValue((...), el.min, el.max, C.UI .. ".slider.set", "value", true)
    if v ~= nil then v = snap(v, el.min, el.max, el.step) end -- min + k * step, as a drag or a commit would give
    if v == el.value then return end -- no UObject call
    el.value = v
    refresh(el, { value = true })
end

function SL.setDefault(h, defaultValue, ...)
    C.enter("slider.setDefault")
    local el = C.element(h, "slider.setDefault", "slider")
    local pre = C.UI .. ".slider.setDefault"
    if select("#", ...) > 1 then C.fail("%s: expected 2 or 3 arguments (handle, defaultValue, hint), got %d", pre, 2 + select("#", ...)) end
    local d = snap(validValue(defaultValue, el.min, el.max, pre, "defaultValue", false), el.min, el.max, el.step)
    -- An omitted hint keeps the current one; an explicit nil clears it.
    local hint = el.hint
    if select("#", ...) == 1 then hint = validHint((...), pre) end
    local moved = d ~= el.default and el.value == nil
    el.default, el.hint = d, hint
    refresh(el, { value = moved, hint = true }) -- a custom value stays where it is
end

function SL.setEnabled(h, enabled)
    C.enter("slider.setEnabled")
    local el = C.element(h, "slider.setEnabled", "slider")
    if type(enabled) ~= "boolean" then C.fail("%s.slider.setEnabled: enabled must be a boolean, got %s", C.UI, C.describe(enabled)) end
    if enabled == el.enabled then return end
    el.enabled = enabled
    refresh(el, { enabled = true })
    X._hostChanged(C.hostOf(el)) -- core story 27: a disabled focused element hands keyboard focus on
end

function SL.setVisible(h, visible)
    C.enter("slider.setVisible")
    local el = C.element(h, "slider.setVisible", "slider")
    if type(visible) ~= "boolean" then C.fail("%s.slider.setVisible: visible must be a boolean, got %s", C.UI, type(visible)) end
    X._setVisible(el, visible)
end

function SL.remove(h)
    C.enter("slider.remove")
    if type(h) == "table" and C.removedHandle[h] then return end -- idempotent
    local el = C.element(h, "slider.remove", "slider")
    X._remove(el)
end

function SL.isShown(h)
    C.enter("slider.isShown")
    local el = C.element(h, "slider.isShown", "slider")
    return X._shown(el)
end

function SL.setTooltip(h, ...) return X._setTooltipOf("slider", h, (...), 1 + select("#", ...)) end

function SL.stats()
    return { ends = S.ends, commits = S.commits, changes = S.changes, restored = S.restored, ignored = S.ignored,
        dropped = S.dropped, throws = S.throws, hooked = S.hooked }
end
SL._end, SL._commit, SL._S, SL._ensureHooks = hookEnd, hookCommit, S, ensureHooks -- unit tests
return SL
