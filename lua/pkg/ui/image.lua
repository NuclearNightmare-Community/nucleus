-- UI-10 (core story 24, core 0.8.0; Mod Manager CAP-2): images. Exposed as core.ui.image on the connect API:
--   create{ id = <string>, place = <intent|nil>, image = <source|nil>, size = n | { w, h } | { w = , h = } | nil,
--           style = { tint = <colour> } | nil, dimmed = <boolean|nil>, tooltip = <tooltip|nil> } -> handle
--   set(handle, { image = <source> | false, dimmed = <boolean> })   only the keys given change; false clears the image
--   setVisible(handle, visible)    remove(handle)    isShown(handle) -> boolean    setTooltip(handle, <tooltip> | nil)
--
-- A source is a table with exactly one key: { icon = <key> } names one of core's own icons, white on transparent
-- textures in core's pak (gear, checkbox-on, checkbox-off, lock, warning, restart), or { game = <path> } one of the
-- game textures in theme.gameTextures, loaded by path at runtime and never shipped. Nothing else is accepted: no mod's
-- own texture, no SVG. Sizes are canvas units, 4 to 512 each way (default 32, square). An image without a source is an
-- empty fixed-size cell (a spacer). The tint (default white: the texture as it is) multiplies the texture; dimmed draws
-- it at the game's disabled colour instead (theme.dimmed). A tooltip needs a host with a cursor (text.lua).
--
-- The widget is WBP_<Core>Image (SizeBox "Box" -> Image "Img"), generated by CoreGen: SetImageTexture(Texture),
-- ClearImageTexture(), SetImageSize(W, H), SetImageTint(R, G, B, A), SetTag (CoreTag, like the other post-v0 kinds).
-- Img is HitTestInvisible unless the image has a tooltip, and its tint's alpha is 0 while it shows no texture (a brush
-- without a texture would draw a white box).
--
-- Textures come from assets.lua: the cache only inside a hook (a menu's Construct; a load there is fatal). A miss there
-- is applied on the next 500 ms UI tick. A texture that can't be loaded logs one WARN per texture per Lua state; the
-- image keeps its size and shows core's icon for the same meaning (theme.gameTextures), else nothing.
--
-- Images go on every host (hud, journal, menu, screen) and in panels, lists and rows (fill allowed); they count toward
-- a container's children; their ids are shared with every other kind.
local BASE = (...):gsub("%.ui%.image$", "")
local C = require(BASE .. ".ui.common")
local H = require(BASE .. ".ui.hud")
local P = require(BASE .. ".ui.place")
local X = require(BASE .. ".ui.text")
local A = require(BASE .. ".ui.assets")
local S = require(BASE .. ".ui.strings")
local theme = require(BASE .. ".ui.theme")

local I = {}
local SIZE_MIN, SIZE_MAX = 4, 512
local CREATE_KEYS = { id = true, place = true, image = true, size = true, style = true, dimmed = true, tooltip = true }
local SET_KEYS = { image = true, dimmed = true }

local function firstLine(e) return (tostring(e):match("^[^\n]*")) end

-- ---------------------------------------------------------------- validation (pure; button.lua shares it)

-- A caller's string in an error, cut at 64 characters (a path is never echoed back whole beyond that).
local function show64(v)
    if type(v) ~= "string" then return C.describe(v) end
    local s = v:sub(1, 64):gsub("[^%w%p ]", "?")
    return string.format("'%s'%s", s, #v > 64 and "..." or "")
end

local GAME_LIST = table.concat(theme.gameTextureNames, ", ")
local ICON_LIST = table.concat(theme.iconNames, ", ")

-- A source: { icon = <key> } or { game = <allow-listed path> }, copied. nil stays nil; allowFalse: false stays false
-- (image.set's "clear"). what names it in errors ("image", "icon").
function I._validSource(v, pre, what, allowFalse)
    if v == nil then return nil end
    if v == false and allowFalse then return false end
    if type(v) ~= "table" then
        C.fail("%s: %s must be { icon = <key> } or { game = <path> }%s, got %s", pre, what, allowFalse and " (or false to clear it)" or "", show64(v))
    end
    local n = 0
    for k in pairs(v) do
        n = n + 1
        if k ~= "icon" and k ~= "game" then C.fail("%s: unknown key %s in %s (valid: game, icon)", pre, show64(k), what) end
    end
    if n ~= 1 then
        C.fail("%s: %s must have exactly one key, icon or game (got %s)", pre, what, n == 0 and "none" or "icon and game")
    end
    if v.icon ~= nil then
        if type(v.icon) ~= "string" or not theme.icons[v.icon] then C.fail("%s: unknown icon %s (valid: %s)", pre, show64(v.icon), ICON_LIST) end
        return { icon = v.icon }
    end
    if type(v.game) ~= "string" or theme.gameTextures[v.game] == nil then
        C.fail("%s: game texture %s is not allow-listed (valid: %s)", pre, show64(v.game), GAME_LIST)
    end
    return { game = v.game }
end

function I._sameSource(a, b)
    if a == nil or b == nil then return a == b end
    return a.icon == b.icon and a.game == b.game
end

-- A size: a number (square) or { w, h } / { w = , h = }, each 4 to 512 canvas units; nil is default x default.
function I._validSize(v, pre, what, default)
    local function bad(detail)
        C.fail("%s: %s must be a number from %d to %d, or { w, h } with each from %d to %d (%s)", pre, what, SIZE_MIN, SIZE_MAX, SIZE_MIN, SIZE_MAX, detail)
    end
    local function num(x) return type(x) == "number" and x == x and x >= SIZE_MIN and x <= SIZE_MAX end
    if v == nil then return { w = default + 0.0, h = default + 0.0 } end
    if type(v) == "number" then
        if not num(v) then bad("got " .. C.describe(v)) end
        return { w = v + 0.0, h = v + 0.0 }
    end
    if type(v) ~= "table" then bad("got " .. show64(v)) end
    for k in pairs(v) do
        if k ~= 1 and k ~= 2 and k ~= "w" and k ~= "h" then bad("unknown key " .. show64(k) .. "; valid: w, h") end
    end
    local w, h
    if v[1] ~= nil or v[2] ~= nil then w, h = v[1], v[2] else w, h = v.w, v.h end
    if not num(w) then bad("w is " .. C.describe(w)) end
    if not num(h) then bad("h is " .. C.describe(h)) end
    return { w = w + 0.0, h = h + 0.0 }
end

function I._validBool(v, pre, what)
    if v == nil then return false end
    if type(v) ~= "boolean" then C.fail("%s: %s must be a boolean or nil, got %s", pre, what, C.describe(v)) end
    return v
end

-- An image's style: { tint = { r = 0..1, g = 0..1, b = 0..1, a = 0..1 (default 1) } }; nil: white.
local function unit(v, what, pre)
    if type(v) ~= "number" or v ~= v or v < 0 or v > 1 then C.fail("%s: style.tint.%s must be a number from 0 to 1, got %s", pre, what, C.describe(v)) end
    return v + 0.0
end
local function validStyle(style, pre)
    local d = theme.imageTint
    if style == nil then return { r = d.r, g = d.g, b = d.b, a = d.a } end
    if type(style) ~= "table" then C.fail("%s: style must be a table { tint = { r, g, b, a } }, got %s", pre, C.describe(style)) end
    for k in pairs(style) do
        if k ~= "tint" then C.fail("%s: unknown style key %s (valid: tint)", pre, C.describe(k)) end
    end
    local t = style.tint
    if t == nil then return { r = d.r, g = d.g, b = d.b, a = d.a } end
    if type(t) ~= "table" then C.fail("%s: style.tint must be a colour table { r = 0..1, g = 0..1, b = 0..1, a = 0..1 }, got %s", pre, C.describe(t)) end
    for k in pairs(t) do
        if k ~= "r" and k ~= "g" and k ~= "b" and k ~= "a" then C.fail("%s: unknown key %s in style.tint (valid: r, g, b, a)", pre, C.describe(k)) end
    end
    return { r = unit(t.r, "r", pre), g = unit(t.g, "g", pre), b = unit(t.b, "b", pre), a = t.a == nil and 1.0 or unit(t.a, "a", pre) }
end

-- ---------------------------------------------------------------- textures (button.lua shares them)

-- The texture for a source: tex, its asset key; or nil, "pending" (inside a hook and not cached: apply on the next
-- tick); or nil, nil (no source, or missing with no fallback: nothing to show). A game texture that can't be loaded
-- falls back to core's icon for the same meaning (assets.lua warned once).
function I._resolve(src)
    if not src then return nil, nil end
    local key = src.icon and ("tex:" .. src.icon) or ("gtex:" .. src.game)
    local tex, why = A.get(key)
    if tex then return tex, key end
    if why == "uncached" then return nil, "pending" end
    local fb = src.game and theme.gameTextures[src.game]
    if fb then
        local fkey = "tex:" .. fb
        tex, why = A.get(fkey)
        if tex then return tex, fkey end
        if why == "uncached" then return nil, "pending" end
    end
    return nil, nil
end

-- Elements whose texture missed the cache inside a hook: el -> fn(el, widget), run on the next UI tick (outside any
-- hook) on the element's live widget. The tick is the shared 500 ms poll (hud.lua), as one more host's dispatch.
local later = {}
function I._later(el, fn) later[el] = fn end
local function flushLater()
    if next(later) == nil then return nil end
    local items = {}
    for el, fn in pairs(later) do items[#items + 1] = { el, fn } end
    for _, it in ipairs(items) do
        local el, fn = it[1], it[2]
        later[el] = nil
        if not el.removed then
            local w = X._liveWidget(el)
            if w then
                local ok, err = pcall(fn, el, w)
                if not ok then C.warnOnce("later:" .. el.id, "%s '%s': applying its texture failed: %s", el.kind, el.id, firstLine(err)) end
            end
        end
    end
    return nil
end
H._host{ poll = function() end, dispatch = flushLater, reset = function() end }
I._flushLater = flushLater -- unit tests

-- ---------------------------------------------------------------- the kind (text.lua's engine)

local function colourKey(c) return string.format("%.4f,%.4f,%.4f,%.4f", c.r, c.g, c.b, c.a) end

-- The tint the widget should have: none (alpha 0) without a texture, the game's disabled colour when dimmed, else the
-- style's tint. el.tintKey: what the widget has now (nil: unknown, as on a fresh widget).
local NO_TINT = { r = 1, g = 1, b = 1, a = 0 }
local function applyTint(el, w, fresh)
    if fresh then el.tintKey = nil end
    local c = (not el.hasTex) and NO_TINT or (el.dimmed and theme.dimmed or el.tint)
    local key = colourKey(c)
    if key == el.tintKey then return end
    C.count(); w:SetImageTint(c.r, c.g, c.b, c.a)
    el.tintKey = key
end

local function applySize(el, w, fresh)
    local key = el.size.w .. "x" .. el.size.h
    if fresh then el.sizeKey = theme.imageSize .. ".0x" .. theme.imageSize .. ".0" end -- the generator's 32x32
    if key == el.sizeKey then return end
    C.count(); w:SetImageSize(el.size.w, el.size.h)
    el.sizeKey = key
end

local function applyTexture(el, w, fresh)
    if fresh then el.appliedTex, el.hasTex = nil, false end -- a fresh widget shows no texture (tint alpha 0)
    local tex, key = I._resolve(el.source)
    if key == "pending" then I._later(el, applyTexture) return end
    local want = tex and key or nil
    if want ~= el.appliedTex then
        if tex then C.count(); w:SetImageTexture(tex) else C.count(); w:ClearImageTexture() end
        el.appliedTex = want
    end
    el.hasTex = tex ~= nil
    applyTint(el, w, false)
end

X.KIND.image = {
    pkg = C.IMAGE_PKG, short = C.IMAGE_SHORT, cls = C.IMAGE_CLASS,
    content = function(el, w, fresh)
        if fresh then el.tintKey = nil end
        applySize(el, w, fresh)
        applyTexture(el, w, fresh)
        X._applyTooltip(el, w, fresh)
    end,
    style = function(el, w) applyTint(el, w, false) end,
}

-- Applies what changed to the live widget, if there is one (create with an existing id, set).
local function refresh(el, what)
    local w = X._liveWidget(el)
    if not w then return end
    local ok, err = pcall(function()
        if what.size then applySize(el, w, false) end
        if what.image then applyTexture(el, w, false) end
        if what.tint then applyTint(el, w, false) end
        if what.tooltip then X._applyTooltip(el, w, false) end
    end)
    if not ok then C.warnOnce("image:" .. el.id, "image '%s': update failed (is %s's pak current?): %s", el.id, C.NAME, firstLine(err)) end
    if what.size then X._resized(el) end
end

-- ---------------------------------------------------------------- public

function I.create(opts, ...)
    C.enter("image.create")
    local pre = C.UI .. ".image.create"
    if type(opts) ~= "table" then C.fail("%s: expected a table { id = ..., place = ..., image = ..., size = ... }, got %s", pre, C.describe(opts)) end
    if select("#", ...) > 0 then C.fail("%s: expected 1 argument (a table), got %d", pre, 1 + select("#", ...)) end
    for k in pairs(opts) do
        if not CREATE_KEYS[k] then C.fail("%s: unknown key %s (valid: dimmed, id, image, place, size, style, tooltip)", pre, C.describe(k)) end
    end
    local id = X._validId(opts.id, "image.create")
    local source = I._validSource(opts.image, pre, "image", false)
    local size = I._validSize(opts.size, pre, "size", theme.imageSize)
    local tint = validStyle(opts.style, pre)
    local dimmed = I._validBool(opts.dimmed, pre, "dimmed")
    local tooltip = S.validateTooltip(opts.tooltip, pre)
    if opts.place ~= nil and type(opts.place) ~= "table" then C.fail("%s: place must be a table or nil, got %s", pre, C.describe(opts.place)) end
    local intent = opts.place or { corner = "top-right" }
    local place = P.validate(intent)
    X._checkTipHost("image", place.panelEl and C.hostOf(place.panelEl) or place.host, tooltip ~= nil)
    local el = X._existing(id, "image", "image.create")
    if el then
        -- Same id: the new source, size, tint, dimmed, tooltip and intent; visibility unchanged.
        el.source, el.size, el.tint, el.dimmed, el.tooltip = source, size, tint, dimmed, tooltip
        if source then A.ensureLoadMapHook() end
        refresh(el, { size = true, image = true, tint = true, tooltip = true })
        P.place(el.handle, intent)
        return el.handle
    end
    if place.panelEl then X._checkJoin(place.panelEl, "image", "image.create", nil, tooltip ~= nil) end
    if source then A.ensureLoadMapHook() end -- story 24: textures in use are preloaded after every map load
    el = X._new("image", id, { source = source, size = size, tint = tint, dimmed = dimmed, tooltip = tooltip }, place)
    return el.handle
end

function I.set(h, changes, ...)
    C.enter("image.set")
    local pre = C.UI .. ".image.set"
    local el = C.element(h, "image.set", "image")
    if select("#", ...) > 0 then C.fail("%s: expected 2 arguments (handle, changes), got %d", pre, 2 + select("#", ...)) end
    if type(changes) ~= "table" then C.fail("%s: changes must be a table { image = <source> | false, dimmed = <boolean> }, got %s", pre, C.describe(changes)) end
    local any = false
    for k in pairs(changes) do
        any = true
        if not SET_KEYS[k] then C.fail("%s: unknown key %s (valid: dimmed, image)", pre, C.describe(k)) end
    end
    if not any then C.fail("%s: changes is empty (give image, dimmed or both)", pre) end
    local source = el.source
    if changes.image ~= nil then
        source = I._validSource(changes.image, pre, "image", true)
        if source == false then source = nil end
    end
    local dimmed = el.dimmed
    if changes.dimmed ~= nil then
        if type(changes.dimmed) ~= "boolean" then C.fail("%s: dimmed must be a boolean, got %s", pre, C.describe(changes.dimmed)) end
        dimmed = changes.dimmed
    end
    local what = {}
    if changes.image ~= nil then
        if not I._sameSource(el.source, source) then el.source = source; what.image = true end
        if source then A.ensureLoadMapHook() end
    end
    if dimmed ~= el.dimmed then el.dimmed = dimmed; what.tint = true end
    if next(what) then refresh(el, what) end -- nothing changed: no UObject call
end

function I.setVisible(h, visible)
    C.enter("image.setVisible")
    local el = C.element(h, "image.setVisible", "image")
    if type(visible) ~= "boolean" then C.fail("%s.image.setVisible: visible must be a boolean, got %s", C.UI, type(visible)) end
    X._setVisible(el, visible)
end

function I.remove(h)
    C.enter("image.remove")
    if type(h) == "table" and C.removedHandle[h] then return end -- idempotent
    local el = C.element(h, "image.remove", "image")
    later[el] = nil
    X._remove(el)
end

function I.isShown(h)
    C.enter("image.isShown")
    local el = C.element(h, "image.isShown", "image")
    return X._shown(el)
end

function I.setTooltip(h, ...) return X._setTooltipOf("image", h, (...), 1 + select("#", ...)) end

I._later_ = later -- unit tests
return I
